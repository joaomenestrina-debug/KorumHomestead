"""The texts that are new or changed since a version, in English and in Portuguese side by side, for a text review.

    python ferramentas/textos_novos.py v2.1.0 docs/tarefas/T5.8-textos.md

Reads Locales.lua at that tag (git show) and as it is now, and writes a Markdown list grouped by the prefix of the key
(fol_, ab_, call_...): key, English, Portuguese. The values keep their codes (%s, %d, |cff...|r) as they are in the
file, so the reviewer sees exactly what the game formats.
"""
import pathlib
import re
import subprocess
import sys

from lupa import lua51

ROOT = pathlib.Path(__file__).resolve().parent.parent


def load(text):
    lua = lua51.LuaRuntime(unpack_returned_tuples=True)
    lua.execute("KH = {}")
    chunk = lua.eval("function(src) return loadstring(src) end")(text)
    chunk("KorumHomestead", lua.eval("KH"))
    tables = lua.eval("KH.L")
    return {lang: dict(tables[lang].items()) for lang in ("enUS", "ptBR")}


def cell(text):
    return (text or "").replace("|", "\\|").replace("\n", " ")


def group(key):
    m = re.match(r"([a-z]+)", key)
    return m.group(1) if m else key


def main(tag, out):
    old = load(subprocess.run(["git", "show", f"{tag}:Locales.lua"], cwd=ROOT, capture_output=True, text=True,
                              encoding="utf-8", check=True).stdout)
    new = load((ROOT / "Locales.lua").read_text(encoding="utf-8"))
    keys = sorted(k for k in new["enUS"]
                  if new["enUS"].get(k) != old["enUS"].get(k) or new["ptBR"].get(k) != old["ptBR"].get(k))
    lines = [f"# Texts new or changed since {tag}", "",
             f"{len(keys)} keys. Generated by `ferramentas/textos_novos.py {tag}`; do not edit this file: edit `Locales.lua`.",
             ""]
    by = {}
    for k in keys:
        by.setdefault(group(k), []).append(k)
    for g in sorted(by):
        lines += [f"## {g}", "", "| Key | English | Português |", "|---|---|---|"]
        for k in by[g]:
            lines.append(f"| `{k}` | {cell(new['enUS'].get(k))} | {cell(new['ptBR'].get(k))} |")
        lines.append("")
    pathlib.Path(out).write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(keys)} textos em {out}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
