function KH.Lang()
    local choice = KH.db and KH.db.lang or "auto"
    if choice == "enUS" or choice == "ptBR" then return choice end
    return (_G.GetLocale and GetLocale() == "ptBR") and "ptBR" or "enUS"
end

function KH.T(key, ...)
    local text = L[KH.Lang()][key] or L.enUS[key] or key
    if select("#", ...) > 0 then
        local ok, out = pcall(string.format, text, ...)
        if ok then return out end
    end
    return text
end

-- 45 -> "45s", 300 -> "5m", 5400 -> "1h 30m"
function KH.Duration(seconds)
    seconds = math.max(0, math.ceil(seconds))
    if seconds < 60 then return seconds .. "s" end
    if seconds < 3600 then return math.ceil(seconds / 60) .. "m" end
    local h, m = math.floor(seconds / 3600), math.ceil((seconds % 3600) / 60)
    if m == 60 then h, m = h + 1, 0 end
    return m > 0 and string.format("%dh %dm", h, m) or (h .. "h")
end

-- 12345 -> "12,345"
function KH.Number(n)
    local s = tostring(math.floor(tonumber(n) or 0))
    local out = s:reverse():gsub("(%d%d%d)", "%1,"):reverse()
    return (out:gsub("^,", ""))
end
